"""Agentic memory tools (Pattern 2).

Each function takes a Supabase client plus the verified ``user_id`` so memories
stay isolated across users. Memories are stored as slots keyed by
``(user_id, memory_type)`` — a UNIQUE constraint backs an upsert, so writing the
same label twice replaces the previous value. Retrieval uses the
``match_memories_hybrid`` Postgres function, which fuses a pgvector cosine
branch with a ``tsvector`` full-text branch via Reciprocal Rank Fusion.
"""

from datetime import datetime, timezone

from supabase import AsyncClient

from tools.embeddings import embed_text


def _now_iso() -> str:
    return datetime.now(tz=timezone.utc).isoformat()


async def remember(
    client: AsyncClient,
    user_id: str,
    memory_type: str,
    content: str,
) -> str:
    """Store or replace the value stored under (user_id, memory_type).

    The embedding joins the label and the content so short-value slots
    ("name": "Pavel") stay semantically findable from natural-language
    queries ("what's the user's name?"). The `fts` column is generated by
    Postgres, so we never write it.
    """
    embedding = await embed_text(f"{memory_type}: {content}")
    await (
        client.table("memories")
        .upsert(
            {
                "user_id": user_id,
                "memory_type": memory_type,
                "content": content,
                "embedding": embedding,
                "updated_at": _now_iso(),
            },
            on_conflict="user_id,memory_type",
        )
        .execute()
    )
    return f"Remembered ({memory_type}): {content}"


async def recall(client: AsyncClient, user_id: str, memory_type: str) -> str:
    """Return the value stored under memory_type, or a 'no memory' message."""
    resp = await (
        client.table("memories")
        .select("content")
        .eq("user_id", user_id)
        .eq("memory_type", memory_type)
        .limit(1)
        .execute()
    )
    rows = resp.data or []
    return rows[0]["content"] if rows else "No memory found."


async def forget(client: AsyncClient, user_id: str, memory_type: str) -> str:
    """Delete the value stored under memory_type."""
    resp = await (
        client.table("memories")
        .delete()
        .eq("user_id", user_id)
        .eq("memory_type", memory_type)
        .execute()
    )
    if not resp.data:
        return "No memory to forget."
    return "Memory forgotten."


async def search_memory(
    client: AsyncClient,
    user_id: str,
    query: str,
    limit: int = 5,
) -> list[dict]:
    """Hybrid vector + text search over the user's memories.

    Calls the `match_memories_hybrid` Postgres function, which runs a pgvector
    cosine branch and a `tsvector` full-text branch, both filtered to
    ``user_id = p_user_id``, and fuses them with Reciprocal Rank Fusion
    (vector weight 0.7, text weight 0.3). The vector branch carries semantic
    intent; the text branch catches literal label hits like "what's my
    user_name?" that pure vector search can miss on short values. Returns
    ``{memory_type, content}`` pairs so callers can follow up via `recall`.
    """
    query_embedding = await embed_text(query)
    resp = await client.rpc(
        "match_memories_hybrid",
        {
            "query_embedding": query_embedding,
            "query_text": query,
            "p_user_id": user_id,
            "match_count": limit,
        },
    ).execute()
    return resp.data or []


async def list_memories(client: AsyncClient, user_id: str) -> list[dict]:
    """Return every slot stored for this user, newest first."""
    resp = await (
        client.table("memories")
        .select("memory_type, content, updated_at")
        .eq("user_id", user_id)
        .order("updated_at", desc=True)
        .execute()
    )
    return resp.data or []
